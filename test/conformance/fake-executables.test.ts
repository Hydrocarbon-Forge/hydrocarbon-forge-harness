import { describe, it, expect, beforeEach, afterEach } from "vitest";
import { mkdtempSync, rmSync, writeFileSync, readFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { execFileSync, spawnSync } from "node:child_process";

const BIN_DIR = resolve(__dirname, "../fixtures/fake-harness/bin");
const BINS = [
  { name: "claude", path: join(BIN_DIR, "claude"), version: "2.1.301" },
  { name: "opencode", path: join(BIN_DIR, "opencode"), version: "opencode 2.0.21" },
  { name: "agy", path: join(BIN_DIR, "agy"), version: "1.4.0" },
];

describe("Fake harness executables", () => {
  let tempDir: string;

  beforeEach(() => {
    tempDir = mkdtempSync(join(tmpdir(), "fake-bin-test-"));
  });

  afterEach(() => {
    try {
      rmSync(tempDir, { recursive: true, force: true });
    } catch {}
  });

  for (const { name, path: binPath, version } of BINS) {
    describe(`${name} executable`, () => {
      it("reports expected pinned version via --version and exits 0 without reading scenario", () => {
        const result = spawnSync(binPath, ["--version"], {
          encoding: "utf8",
          env: { PATH: process.env.PATH },
        });
        expect(result.status).toBe(0);
        expect(result.stdout.trim()).toBe(version);
      });

      it("edits out.txt on disk from call 0 of the scenario file", () => {
        const scenarioFile = join(tempDir, "scenario.json");
        const expectedText = `content generated by ${name} executable test`;
        writeFileSync(
          scenarioFile,
          JSON.stringify({
            calls: [
              {
                edits: { "out.txt": expectedText },
                reply: "OK",
              },
            ],
          }),
          "utf8"
        );

        const result = spawnSync(binPath, ["-p", "please generate out.txt"], {
          cwd: tempDir,
          encoding: "utf8",
          env: {
            ...process.env,
            FAKE_SCENARIO_FILE: scenarioFile,
          },
        });

        expect(result.status).toBe(0);
        const outPath = join(tempDir, "out.txt");
        expect(existsSync(outPath)).toBe(true);
        expect(readFileSync(outPath, "utf8")).toBe(expectedText);
      });

      it("advances counter state and handles multi-call scenarios (edits then appends)", () => {
        const scenarioFile = join(tempDir, "scenario.json");
        writeFileSync(
          scenarioFile,
          JSON.stringify({
            calls: [
              {
                edits: { "seq.txt": "first\n" },
                reply: "first done",
              },
              {
                append: { "seq.txt": "second\n" },
                reply: "second done",
              },
            ],
          }),
          "utf8"
        );

        // Call 0
        const res1 = spawnSync(binPath, ["-p", "turn 1"], {
          cwd: tempDir,
          encoding: "utf8",
          env: { ...process.env, FAKE_SCENARIO_FILE: scenarioFile },
        });
        expect(res1.status).toBe(0);
        expect(readFileSync(join(tempDir, "seq.txt"), "utf8")).toBe("first\n");

        const statePath = `${scenarioFile}.state.json`;
        expect(existsSync(statePath)).toBe(true);
        expect(JSON.parse(readFileSync(statePath, "utf8"))).toEqual({ next: 1 });

        // Call 1
        const res2 = spawnSync(binPath, ["-p", "turn 2"], {
          cwd: tempDir,
          encoding: "utf8",
          env: { ...process.env, FAKE_SCENARIO_FILE: scenarioFile },
        });
        expect(res2.status).toBe(0);
        expect(readFileSync(join(tempDir, "seq.txt"), "utf8")).toBe("first\nsecond\n");
        expect(JSON.parse(readFileSync(statePath, "utf8"))).toEqual({ next: 2 });
      });

      it("writes plan.files before any other step", () => {
        const scenarioFile = join(tempDir, "scenario.json");
        writeFileSync(
          scenarioFile,
          JSON.stringify({
            calls: [
              {
                plan: {
                  files: {
                    "nested/plan.yaml": "tasks:\n  - r0.2\n",
                  },
                },
                edits: { "result.txt": "done" },
                reply: "planned",
              },
            ],
          }),
          "utf8"
        );

        const result = spawnSync(binPath, ["-p", "run plan"], {
          cwd: tempDir,
          encoding: "utf8",
          env: { ...process.env, FAKE_SCENARIO_FILE: scenarioFile },
        });

        expect(result.status).toBe(0);
        expect(readFileSync(join(tempDir, "nested/plan.yaml"), "utf8")).toBe(
          "tasks:\n  - r0.2\n"
        );
        expect(readFileSync(join(tempDir, "result.txt"), "utf8")).toBe("done");
      });

      it("fails with exit code 3 when FAKE_SCENARIO_FILE is not set", () => {
        const envWithout = { ...process.env };
        delete envWithout.FAKE_SCENARIO_FILE;

        const result = spawnSync(binPath, ["-p", "test"], {
          cwd: tempDir,
          encoding: "utf8",
          env: envWithout,
        });

        expect(result.status).toBe(3);
        expect(result.stderr).toContain("fake-harness: FAKE_SCENARIO_FILE not set");
      });

      it("fails with exit code 3 when FAKE_SCENARIO_FILE does not exist", () => {
        const result = spawnSync(binPath, ["-p", "test"], {
          cwd: tempDir,
          encoding: "utf8",
          env: { ...process.env, FAKE_SCENARIO_FILE: "/nonexistent/scenario.json" },
        });

        expect(result.status).toBe(3);
        expect(result.stderr).toContain(
          "fake-harness: FAKE_SCENARIO_FILE not found: /nonexistent/scenario.json"
        );
      });

      it("fails with exit code 3 when calls is exhausted or empty", () => {
        const scenarioFile = join(tempDir, "empty.json");
        writeFileSync(scenarioFile, JSON.stringify({ calls: [] }), "utf8");

        const result = spawnSync(binPath, ["-p", "test"], {
          cwd: tempDir,
          encoding: "utf8",
          env: { ...process.env, FAKE_SCENARIO_FILE: scenarioFile },
        });

        expect(result.status).toBe(3);
        expect(result.stderr).toContain("fake-harness: scenario has no call 0");
      });

      it("rejects absolute or path traversal edits with exit code 3", () => {
        const scenarioFile = join(tempDir, "unsafe.json");
        writeFileSync(
          scenarioFile,
          JSON.stringify({
            calls: [
              {
                edits: { "../escaped.txt": "bad" },
              },
            ],
          }),
          "utf8"
        );

        const result = spawnSync(binPath, ["-p", "test"], {
          cwd: tempDir,
          encoding: "utf8",
          env: { ...process.env, FAKE_SCENARIO_FILE: scenarioFile },
        });

        expect(result.status).toBe(3);
        expect(result.stderr).toContain("fake-harness: unsafe path ../escaped.txt");
      });

      it("handles failure: crash with stderr output and exit code 1", () => {
        const scenarioFile = join(tempDir, "crash.json");
        writeFileSync(
          scenarioFile,
          JSON.stringify({
            calls: [{ failure: "crash" }],
          }),
          "utf8"
        );

        const result = spawnSync(binPath, ["-p", "test"], {
          cwd: tempDir,
          encoding: "utf8",
          env: { ...process.env, FAKE_SCENARIO_FILE: scenarioFile },
        });

        expect(result.status).toBe(1);
        expect(result.stderr).toContain("fake-harness: simulated crash");
        expect(result.stdout).toBe("");
      });

      it("handles failure: rate_limit with exit code 1", () => {
        const scenarioFile = join(tempDir, "rate_limit.json");
        writeFileSync(
          scenarioFile,
          JSON.stringify({
            calls: [{ failure: "rate_limit" }],
          }),
          "utf8"
        );

        const result = spawnSync(binPath, ["-p", "test"], {
          cwd: tempDir,
          encoding: "utf8",
          env: { ...process.env, FAKE_SCENARIO_FILE: scenarioFile },
        });

        expect(result.status).toBe(1);
        expect(result.stdout.toLowerCase()).toMatch(/rate[-_ ]limit/);
      });
    });
  }

  describe("Dialect-specific behaviors", () => {
    it("claude rejects invalid UUID session id with exit 1 (verified against real Claude CLI)", () => {
      const scenarioFile = join(tempDir, "scenario.json");
      writeFileSync(
        scenarioFile,
        JSON.stringify({
          calls: [{ reply: "OK" }],
        }),
        "utf8"
      );

      const result = spawnSync(
        join(BIN_DIR, "claude"),
        ["--session-id", "not-a-valid-uuid", "-p", "hi"],
        {
          cwd: tempDir,
          encoding: "utf8",
          env: { ...process.env, FAKE_SCENARIO_FILE: scenarioFile },
        }
      );

      expect(result.status).toBe(1);
      expect(result.stderr).toContain("Error: Invalid session ID. Must be a valid UUID.");
    });

    it("claude emits permission denial system event and permission_denials result entry", () => {
      const scenarioFile = join(tempDir, "claude-denial.json");
      writeFileSync(
        scenarioFile,
        JSON.stringify({
          calls: [{ failure: "permission_denial", reply: "Denial observed" }],
        }),
        "utf8"
      );

      const result = spawnSync(
        join(BIN_DIR, "claude"),
        ["--session-id", "12345678-1234-1234-1234-123456789abc", "-p", "run"],
        {
          cwd: tempDir,
          encoding: "utf8",
          env: { ...process.env, FAKE_SCENARIO_FILE: scenarioFile },
        }
      );

      expect(result.status).toBe(0);
      const lines = result.stdout.trim().split("\n").map((l) => JSON.parse(l));
      const denialEvent = lines.find(
        (l) => l.type === "system" && l.subtype === "permission_denied"
      );
      expect(denialEvent).toBeDefined();
      expect(denialEvent.tool_name).toBe("Bash");

      const resultEvent = lines.find((l) => l.type === "result");
      expect(resultEvent).toBeDefined();
      expect(resultEvent.permission_denials).toHaveLength(1);
      expect(resultEvent.permission_denials[0].tool_name).toBe("Bash");
    });

    it("opencode emits text without tool events on permission denial", () => {
      const scenarioFile = join(tempDir, "opencode-denial.json");
      writeFileSync(
        scenarioFile,
        JSON.stringify({
          calls: [{ failure: "permission_denial" }],
        }),
        "utf8"
      );

      const result = spawnSync(
        join(BIN_DIR, "opencode"),
        ["-s", "ses_test123456", "run", "prompt"],
        {
          cwd: tempDir,
          encoding: "utf8",
          env: { ...process.env, FAKE_SCENARIO_FILE: scenarioFile },
        }
      );

      expect(result.status).toBe(0);
      const lines = result.stdout.trim().split("\n").map((l) => JSON.parse(l));
      expect(lines.some((l) => l.type === "tool_use")).toBe(false);
      const textEvent = lines.find((l) => l.type === "text");
      expect(textEvent).toBeDefined();
      expect(textEvent.part.text).toContain("no shell/bash tool is available");
    });

    it("agy emits jetski stderr line and denied_actions on permission denial", () => {
      const scenarioFile = join(tempDir, "agy-denial.json");
      writeFileSync(
        scenarioFile,
        JSON.stringify({
          calls: [{ failure: "permission_denial" }],
        }),
        "utf8"
      );

      const result = spawnSync(
        join(BIN_DIR, "agy"),
        ["--conversation", "33333333-4444-5555-6666-777777777777", "-p", "run"],
        {
          cwd: tempDir,
          encoding: "utf8",
          env: { ...process.env, FAKE_SCENARIO_FILE: scenarioFile },
        }
      );

      expect(result.status).toBe(0);
      expect(result.stderr).toContain("jetski: no output produced");
      const lines = result.stdout.trim().split("\n").map((l) => JSON.parse(l));
      const resultEvent = lines.find((l) => l.event === "result");
      expect(resultEvent).toBeDefined();
      expect(resultEvent.result.denied_actions).toBeDefined();
      expect(resultEvent.result.denied_actions[0].action).toBe("command");
    });
  });
});
